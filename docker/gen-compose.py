#!/usr/bin/env python3
"""Generate docker-compose.yml from the official release/kubernetes-manifests.yaml.

Everything (images, env vars, ports, resources, security context, the
loadgenerator init container) is parsed from the manifest, so nothing is
written from memory. K8s Service names are kept as compose service names, and
"service:servicePort" addresses are rewritten to "service:containerPort"
because compose has no Service port indirection (e.g. emailservice 5000->8080,
frontend 80->8080).

Usage: python3 gen-compose.py [MANIFEST] [OUTPUT] [HOST_PORT]
"""
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    HERE, "..", "microservices-demo", "release", "kubernetes-manifests.yaml")
OUTPUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "docker-compose.yml")
HOST_PORT = sys.argv[3] if len(sys.argv) > 3 else "8080"

docs = [d for d in yaml.safe_load_all(open(MANIFEST)) if d]
deployments = {d["metadata"]["name"]: d for d in docs if d["kind"] == "Deployment"}
services = {d["metadata"]["name"]: d for d in docs if d["kind"] == "Service"}

# Map "<service>:<servicePort>" -> "<deployment>:<targetPort>"
addr_map = {}
for name, svc in services.items():
    target = svc["spec"]["selector"]["app"]
    for p in svc["spec"]["ports"]:
        addr_map[f"{name}:{p['port']}"] = f"{target}:{p.get('targetPort', p['port'])}"

ADDR_RE = re.compile(r"^([a-z0-9-]+):(\d+)$")
unresolved = []


def translate(value):
    m = ADDR_RE.match(str(value))
    if not m:
        return str(value)
    if value in addr_map:
        return addr_map[value]
    unresolved.append(value)  # e.g. shoppingassistantservice (not deployed)
    return str(value)


def cpu(v):
    v = str(v)
    return str(int(v[:-1]) / 1000) if v.endswith("m") else v


def mem(v):
    return str(v).replace("Mi", "m").replace("Gi", "g")


def common(c, pod_sc):
    out = {}
    sc = c.get("securityContext", {}) or {}
    if pod_sc.get("runAsUser") is not None:
        out["user"] = f"{pod_sc['runAsUser']}:{pod_sc.get('runAsGroup', pod_sc['runAsUser'])}"
    if sc.get("readOnlyRootFilesystem"):
        out["read_only"] = True
    if sc.get("capabilities", {}).get("drop"):
        out["cap_drop"] = sc["capabilities"]["drop"]
    if sc.get("allowPrivilegeEscalation") is False:
        out["security_opt"] = ["no-new-privileges:true"]
    lim = (c.get("resources") or {}).get("limits", {})
    if "cpu" in lim:
        out["cpus"] = cpu(lim["cpu"])
    if "memory" in lim:
        out["mem_limit"] = mem(lim["memory"])
    return out


compose = {"name": "boutique", "services": {}}
for name, dep in deployments.items():
    spec = dep["spec"]["template"]["spec"]
    pod_sc = spec.get("securityContext", {}) or {}
    c = spec["containers"][0]
    svc = {"image": c["image"]}
    env = {e["name"]: translate(e["value"]) for e in c.get("env", [])}
    if env:
        svc["environment"] = env
    if c.get("command"):
        svc["entrypoint"] = c["command"]
    if c.get("args"):
        svc["command"] = c["args"]
    svc.update(common(c, pod_sc))
    # emptyDir volumes -> tmpfs owned by the pod user (needed with read_only)
    vols = {v["name"]: v for v in spec.get("volumes", []) or []}
    tmpfs = []
    for vm in c.get("volumeMounts", []) or []:
        if "emptyDir" in vols.get(vm["name"], {}):
            uid = pod_sc.get("runAsUser", 0)
            tmpfs.append(f"{vm['mountPath']}:uid={uid},gid={pod_sc.get('fsGroup', uid)}")
    if tmpfs:
        svc["tmpfs"] = tmpfs
    if name == "frontend":
        svc["ports"] = [f"{HOST_PORT}:{c['ports'][0]['containerPort']}"]
    svc["restart"] = "unless-stopped"

    if name == "loadgenerator":
        svc["profiles"] = ["load"]
        for ic in spec.get("initContainers", []) or []:
            init = {"image": ic["image"], "profiles": ["load"], "restart": "no"}
            init["environment"] = {e["name"]: translate(e["value"]) for e in ic.get("env", [])}
            init["entrypoint"] = ic["command"]
            init.update(common(ic, pod_sc))
            init["depends_on"] = ["frontend"]
            iname = f"loadgenerator-init-{ic['name']}"
            compose["services"][iname] = init
            svc.setdefault("depends_on", {})[iname] = {"condition": "service_completed_successfully"}
    compose["services"][name] = svc


class Dumper(yaml.SafeDumper):
    pass


def str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, str_presenter)

with open(OUTPUT, "w") as f:
    f.write("# GENERATED by gen-compose.py from microservices-demo/release/kubernetes-manifests.yaml\n")
    f.write("# Do not edit by hand; re-run: python3 docker/gen-compose.py\n")
    # `$` in the init script must reach the container shell, not compose interpolation
    text = yaml.dump(compose, Dumper=Dumper, sort_keys=False, width=1000)
    f.write(text.replace("$", "$$"))

print(f"wrote {OUTPUT} ({len(compose['services'])} services)")
print("address translations:", {k: v for k, v in addr_map.items() if k != v})
if unresolved:
    print("WARNING unresolved addresses (kept as-is, same as in K8s):", sorted(set(unresolved)))
